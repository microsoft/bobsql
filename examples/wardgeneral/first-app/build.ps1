#requires -Version 7.0
<#
    Ward General Hospital Digital Chart Application
    build.ps1 : build the .NET application.

    Usage:
      ./build.ps1                          # dotnet build (Debug)
      ./build.ps1 -Configuration Release   # release build
      ./build.ps1 -Clean                   # delete build output first, then build
      ./build.ps1 -Publish                 # dotnet publish to src/WardGeneral.Web/publish
      ./build.ps1 -SkipPreflight           # skip the toolchain checks
#>
[CmdletBinding()]
param(
    [ValidateSet('Debug', 'Release')]
    [string]$Configuration = 'Debug',

    [switch]$Clean,

    [switch]$Publish,

    [switch]$SkipPreflight
)

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$solution = Join-Path $root 'WardGeneral.slnx'
$webProj = Join-Path $root 'src' 'WardGeneral.Web' 'WardGeneral.Web.csproj'

if (-not (Test-Path $webProj)) {
    throw "Web project not found: $webProj"
}

# -- Pre-flight: local toolchain only. Building does not need an Azure sign-in,
# a firewall rule, or a database, so a cloud problem must never fail a build.
# Those checks belong to run.ps1, which calls preflight-run.ps1.
if (-not $SkipPreflight) {
    & (Join-Path $root 'preflight-build.ps1')
    if ($LASTEXITCODE -ne 0) {
        throw "Build pre-flight failed. Fix the problems above, or re-run with -SkipPreflight."
    }
}

# -- Clean. Deliberately not `dotnet clean`, which only removes what the last
# build recorded and so tends to leave behind the very stale assembly you are
# trying to get rid of. Deleting bin/obj outright is the reliable form, and it
# is safe: everything in them is regenerated by the next build.
if ($Clean) {
    Write-Host "Cleaning build output..." -ForegroundColor Cyan
    $stale = Get-ChildItem -Path (Join-Path $root 'src') -Directory -Recurse -ErrorAction SilentlyContinue |
        Where-Object { $_.Name -in 'bin', 'obj', 'publish' }
    foreach ($dir in $stale) {
        if (Test-Path $dir.FullName) {
            Write-Host "  removing $($dir.FullName.Substring($root.Length + 1))" -ForegroundColor DarkGray
            Remove-Item $dir.FullName -Recurse -Force -ErrorAction SilentlyContinue
        }
    }
}

Write-Host "Building the solution ($Configuration)..." -ForegroundColor Cyan
dotnet build $solution -c $Configuration --nologo
if ($LASTEXITCODE -ne 0) { throw "dotnet build failed (exit $LASTEXITCODE)." }

if ($Publish) {
    $out = Join-Path $root 'src' 'WardGeneral.Web' 'publish'
    Write-Host "Publishing the web app to $out..." -ForegroundColor Cyan
    dotnet publish $webProj -c $Configuration -o $out --nologo
    if ($LASTEXITCODE -ne 0) { throw "dotnet publish failed (exit $LASTEXITCODE)." }
}

Write-Host "Build succeeded." -ForegroundColor Green
